#!/usr/bin/env python3
"""Generate a deterministic synthetic paired-end SAM dataset for msamtools validation.

This script is the second stage of the reproducible msamtools validation-data
workflow. It consumes chromosome-only genomes prepared by ``prepare_genomes.py``
and generates a realistic but controlled metagenomic alignment dataset for
Tier-2 validation of msamtools abundance profiling.

The simulator works directly in alignment space; it does NOT call a read mapper.
This is intentional. Exact source and alternative alignments are known by
construction, allowing the resulting SAM file to have fully traceable ground
truth without introducing mapper-specific heuristics.

Simulation model
----------------
* Paired-end reads: 2 x 100 bp.
* Insert length: 175 bp (25 bp mate overlap).
* Alignments use CIGAR ``100M`` only.
* Each mate independently receives 0, 1, 2, or 3 substitutions.
* Source genomes are sampled proportional to:
      true cell abundance x chromosome length
  so length-normalized profiling can be compared with the known cell abundance.
* Exact multi-mappers are identified from genuine identical 175-bp chromosome
  segments. Candidate inserts are sampled first, then all chromosomes are
  scanned once with a rolling 2-bit encoder to find exact occurrences.
* A configurable fraction of inserts is deliberately drawn from shared loci to
  ensure that multi-mapper handling receives adequate validation coverage.
* A configurable fraction of inserts contains only one mapped mate. These
  inserts are emitted with a single mapped SAM record so that profiling in
  insert space is represented in the validation data.
* SAM records are grouped by QNAME, as required by msamtools ``profile``.

This script deliberately does NOT test clipping, indels, malformed/missing SAM
tags, unmapped-read handling, threshold boundaries, coordinate-sort rejection,
or other exact CLI/error semantics. Those belong to the Tier-1 test suite.

Usage
-----
Typical use::

    python3 generate_synthetic_alignments.py \
        prepared_genomes/validated_genomes.tsv \
        community_abundances.tsv

Choose the number of simulated inserts and random seed::

    python3 generate_synthetic_alignments.py \
        prepared_genomes/validated_genomes.tsv \
        community_abundances.tsv \
        --num-inserts 10000 \
        --seed 13579

Change the deliberately enriched shared-locus fraction::

    python3 generate_synthetic_alignments.py \
        prepared_genomes/validated_genomes.tsv \
        community_abundances.tsv \
        --shared-fraction 0.20

Change mismatch-class probabilities::

    python3 generate_synthetic_alignments.py \
        prepared_genomes/validated_genomes.tsv \
        community_abundances.tsv \
        --mismatch-weights 0:0.50,1:0.30,2:0.10,3:0.10

Exclude repeats confined to a single genome while retaining cross-genome
multi-mappers::

    python3 generate_synthetic_alignments.py \
        prepared_genomes/validated_genomes.tsv \
        community_abundances.tsv \
        --exclude-within-genome-repeats

Exclude all cross-genome multimappers for a strict no-sharing control::

    python3 generate_synthetic_alignments.py \
        prepared_genomes/validated_genomes.tsv \
        community_abundances.tsv \
        --shared-fraction 0 \
        --exclude-cross-genome-multimappers

Input: validated_genomes.tsv
----------------------------
The validation report produced by ``prepare_genomes.py``. Required columns are::

    assembly_accession
    expected_species
    expected_strain
    chromosome_accession
    chromosome_length
    fasta_path
    status

Only rows with ``status=PASS`` are accepted.

Input: community_abundances.tsv
-------------------------------
A tab-separated file with::

    assembly_accession    relative_abundance

Abundances must be positive and sum to 1 within a small numerical tolerance.
Every validated genome must occur exactly once.

Outputs
-------
By default, ``synthetic_validation/`` contains:

``alignments.sam``
    QNAME-grouped paired-end SAM suitable for msamtools profiling.
``community_truth.tsv``
    Cell abundance, chromosome length, DNA fraction, and realized source counts.
``insert_sources.tsv``
    Minimal per-insert source truth: QNAME, source assembly, and mate status.
``reference_metadata.tsv``
    Reference, assembly, species, strain, and safe feature identifiers.
``reference_to_species.tsv``
    Two-column msamtools genome-definition file collapsing strains to species.
``reference_to_strain.tsv``
    Two-column msamtools genome-definition file retaining strain-level features.
``multimapping_pairs.tsv``
    Counts of cross-genome ambiguous inserts for each target-genome pair.
``simulation_summary.tsv``
    Machine-readable key/value summary of the realized dataset, including
    single-locus, same-genome-repeat, and cross-genome ambiguity classes.

Requirements
------------
* Python 3.9 or newer.
* No third-party Python packages.
* Chromosome FASTAs generated by ``prepare_genomes.py``.

Reproducibility notes
---------------------
All random choices use a dedicated ``random.Random`` instance seeded by
``--seed``. Sets and mappings are sorted before randomized selection or output
where ordering could otherwise depend on hash iteration order.

The exact-matching index is deliberately query-driven rather than genome-wide:
candidate inserts are sampled first, their 175-bp sequences are encoded, and
the chromosomes are then scanned with a rolling 2-bit representation. This
keeps memory use proportional to the candidate pool instead of storing tens of
millions of genome-wide k-mers.
"""

from __future__ import annotations

import argparse
import csv
import math
import random
import re
import sys
from collections import Counter, defaultdict
from itertools import combinations
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable, Iterator, Sequence


READ_LENGTH = 100
INSERT_LENGTH = 175
MATE_OFFSET = INSERT_LENGTH - READ_LENGTH  # 75 bp
DEFAULT_MISMATCH_WEIGHTS = "0:0.50,1:0.30,2:0.10,3:0.10"
DNA_BASES = "ACGT"
COMPLEMENT = str.maketrans("ACGT", "TGCA")

REQUIRED_GENOME_COLUMNS = {
    "assembly_accession",
    "expected_species",
    "expected_strain",
    "chromosome_accession",
    "chromosome_length",
    "fasta_path",
    "status",
}
REQUIRED_ABUNDANCE_COLUMNS = {"assembly_accession", "relative_abundance"}


@dataclass(frozen=True)
class Genome:
    """One validated chromosome used as a simulation reference."""

    assembly_accession: str
    species: str
    strain: str
    chromosome_accession: str
    sequence: str
    fasta_path: Path

    @property
    def length(self) -> int:
        """Return chromosome length in bases."""

        return len(self.sequence)


@dataclass(frozen=True)
class Occurrence:
    """One exact occurrence of a candidate insert in a reference chromosome."""

    assembly_accession: str
    start: int  # zero-based leftmost coordinate on the reference
    orientation: str  # '+' if candidate sequence matches reference, '-' if RC matches


@dataclass(frozen=True)
class Candidate:
    """One candidate source insert sampled before final dataset selection."""

    source_assembly: str
    source_start: int
    fragment_code: int


@dataclass
class SelectedInsert:
    """A finalized insert and its exact reference occurrences."""

    qname: str
    source_assembly: str
    source_start: int
    fragment_code: int
    occurrences: list[Occurrence]
    selection_mode: str
    mate_status: str = "both_mapped"
    mate1_nm: int = 0
    mate2_nm: int = 0


